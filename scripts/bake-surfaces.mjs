// Bake every surface source into its committed canonical PNG + rebuild the manifest.
// Surfaces are HTML/CSS artifacts (packages/assets/surfaces/<name>/source.html) rendered
// once by the motion recorder's pinned Chromium; films consume ONLY the committed art.png
// (Chromium rasterization is not cross-platform byte-stable — the PNG is the asset, the
// HTML is its regeneration recipe). See docs/plan-surface-pack.md.
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { join } from "node:path";
import { captureStill, recordFrames } from "../packages/motion/record.mjs";

const root = new URL("../packages/assets/surfaces/", import.meta.url).pathname;
const entries = [];
for (const dir of (await readdir(root, { withFileTypes: true })).filter((d) => d.isDirectory())) {
  const base = join(root, dir.name);
  const meta = JSON.parse(await readFile(join(base, "surface.json"), "utf8"));
  const [width, height] = meta.size;
  if (meta.type === "anim") {
    // Animated surface: source.html implements the recorder's film contract
    // (window.__film = { fps, frames, seek }); every frame is a committed asset.
    await mkdir(join(base, "frames"), { recursive: true });
    let count = 0;
    await recordFrames(join(base, "source.html"), { width, height, from: 0, to: meta.frames - 1 }, {
      onFrame: async (png, f) => {
        await writeFile(join(base, "frames", `f_${String(f).padStart(3, "0")}.png`), png);
        if (f === 0) await writeFile(join(base, "art.png"), png); // static fallback bake
        count++;
      },
    });
    if (count !== meta.frames) throw new Error(`${meta.name}: baked ${count} frames, surface.json declares ${meta.frames}`);
    console.log(`✓ ${meta.name} (anim — ${count} frames @ ${meta.fps} fps, ${width}x${height})`);
  } else if (meta.type !== "svg") {
    const png = await captureStill(join(base, "source.html"), { width, height });
    await writeFile(join(base, "art.png"), png);
    console.log(`✓ ${meta.name} (${width}x${height}, ${png.length} bytes)`);
  } else {
    console.log(`✓ ${meta.name} (svg — consumed as geometry, no bake)`);
  }
  entries.push({
    name: meta.name, type: meta.type ?? "html", size: meta.size, license: meta.license,
    ...(meta.type === "anim" ? { fps: meta.fps, frames: meta.frames } : {}),
    ...(meta.prompt ? { prompt: meta.prompt } : {}),
  });
}
entries.sort((a, b) => a.name.localeCompare(b.name));
await writeFile(join(root, "manifest.json"), JSON.stringify({ surfaces: entries }, null, 2) + "\n");
console.log(`✓ manifest — ${entries.length} surfaces`);

// Codegen the synchronous name table film3d's zod schema validates `art` against
// (the same generated-file trick as characters.extra.ts — schemas can't do async IO).
const table = `// GENERATED by scripts/bake-surfaces.mjs — do not edit by hand.
export const SURFACE_NAMES = ${JSON.stringify(entries.filter((e) => e.type === "html").map((e) => e.name))} as const;
export const CUTOUT_NAMES = ${JSON.stringify(entries.filter((e) => e.type === "svg").map((e) => e.name))} as const;
export const SCREEN_NAMES = ${JSON.stringify(entries.filter((e) => e.type === "anim").map((e) => e.name))} as const;
`;
await writeFile(new URL("../packages/film3d/src/surfaces.ts", import.meta.url).pathname, table);
console.log("✓ packages/film3d/src/surfaces.ts (codegen)");
