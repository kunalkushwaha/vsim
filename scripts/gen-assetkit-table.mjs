#!/usr/bin/env node
// Codegen the synchronous assetkit name table film3d's zod schema validates against
// (schemas can't do async IO — same trick as surfaces.ts). Run after make.py adds a model:
//   pnpm gen:assetkit
import { readFile, writeFile } from "node:fs/promises";

const manifest = new URL("../packages/assets/models/assetkit/manifest.json", import.meta.url);
const out = new URL("../packages/film3d/src/assetkit.ts", import.meta.url);
const { models } = JSON.parse(await readFile(manifest, "utf8"));
const sorted = [...models].sort((a, b) => a.name.localeCompare(b.name));
const r3 = (v) => v.map((x) => Math.round(x * 1000) / 1000);
const table = Object.fromEntries(sorted.map((m) => [m.name, { kind: m.kind, size_m: r3(m.size_m) }]));
const names = (kind) => JSON.stringify(sorted.filter((m) => m.kind === kind).map((m) => m.name));
const src = `// GENERATED by scripts/gen-assetkit-table.mjs from packages/assets/models/assetkit/manifest.json — do not edit by hand.
/** assetkit library models: kind + exported size in metres [width x, height y, depth z] (1 film unit = 1 m). */
export const ASSETKIT_MODELS: Record<string, { kind: string; size_m: readonly [number, number, number] }> = ${JSON.stringify(table)};
export const ASSETKIT_BUILDINGS = ${names("building")} as const;
export const ASSETKIT_FLOWERS = ${names("flower")} as const;
`;
await writeFile(out, src);
console.log(`✓ packages/film3d/src/assetkit.ts — ${sorted.length} models`);
